use std::path::{Path, PathBuf};

/// First line of every generated source.
pub(crate) const MARKER: &str = "; Generated by nesasm disassembler";
/// Indentation of instructions and directives.
const INDENT: &str = "\t";
/// Bytes shown per source line.
const SHOWN_BYTES: usize = 8;
/// Bytes of text per `.db` line.
const TEXT_PER_LINE: usize = 32;
/// Larger sources are split into a file per bank (the assembler reads
/// files up to 1 MiB; this leaves room for editing).
const SPLIT_SIZE: usize = 512 * 1024;

pub(crate) struct Rendered {
    /// Source files (the main file first) by path relative to the working directory.
    pub files: Vec<(PathBuf, String)>,
    /// Lines of all files in assembly order, without the marker lines.
    pub lines: Vec<SourceLine>,
    /// The CHR file `.incbin` reads, and its contents.
    pub chr: Option<(PathBuf, Vec<u8>)>,
}

/// FNV-1a over the text after the marker line, with LF line endings.
pub(crate) fn checksum(body: &str) -> u64 {
    fnv(body.replace("\r\n", "\n").bytes())
}

fn fnv(bytes: impl Iterator<Item = u8>) -> u64 {
    bytes.fold(0xcbf2_9ce4_8422_2325, |hash, b| {
        (hash ^ u64::from(b)).wrapping_mul(0x0100_0000_01b3)
    })
}

/// Line of the main source recording the CHR file's checksum.
const CHR_LINE: &str = "; CHR file checksum ";

/// Whether `chr` is the CHR file the generated source `text` records.
pub(crate) fn is_unedited_chr(text: &str, chr: &[u8]) -> bool {
    text.lines()
        .find_map(|line| line.trim_end().strip_prefix(CHR_LINE))
        .and_then(|sum| u64::from_str_radix(sum, 16).ok())
        .is_some_and(|sum| sum == fnv(chr.iter().copied()))
}

/// Whether `text` is a generated source that has not been edited since.
pub(crate) fn is_unedited(text: &str) -> bool {
    let Some((first, body)) = text.split_once('\n') else {
        return false;
    };
    first
        .trim_end()
        .strip_prefix(MARKER)
        .and_then(|rest| rest.rsplit_once("checksum "))
        .and_then(|(_, sum)| u64::from_str_radix(sum.trim(), 16).ok())
        .is_some_and(|sum| sum == checksum(body))
}

/// What a generated source is.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Role {
    /// The main file (its body starts with the `; Source:` line).
    Main,
    /// The file of one bank (its body starts with `.bank n`).
    Bank(usize),
}

/// The role of a generated source that has not been edited since. Bank
/// files are told apart by their `.bank` line, not by their name: the
/// decimal names of older versions (`_bank10` for bank 10) name other banks
/// in hexadecimal.
pub(crate) fn role(text: &str) -> Option<Role> {
    if !is_unedited(text) {
        return None;
    }
    let first = text.lines().nth(1)?;
    if first.starts_with(SOURCE_LINE) {
        return Some(Role::Main);
    }
    let bank = first.trim_start().strip_prefix(".bank ")?;
    bank.trim().parse().ok().map(Role::Bank)
}

/// The `.include`d paths of a generated main source.
pub(crate) fn includes(text: &str) -> Vec<String> {
    text.lines()
        .filter_map(|line| line.trim_start().strip_prefix(".include \""))
        .filter_map(|rest| rest.trim_end().strip_suffix('"'))
        .map(str::to_owned)
        .collect()
}

/// First line of the main source's body.
const SOURCE_LINE: &str = "; Source: ";

struct Writer<'a> {
    a: &'a Analysis,
    lines: Vec<SourceLine>,
    /// Symbols (outside the ROM) the code refers to.
    used: BTreeSet<String>,
    /// Offsets of each bank where a data line must end: labels, comments,
    /// operands, region bounds, instructions and patch ranges.
    stops: Vec<Vec<usize>>,
    /// For a ROM hack, the ranges written as source.
    patches: Option<&'a Patches>,
    /// Labels the source refers to, with their locations.
    used_labels: BTreeMap<String, Loc>,
}

/// A path as written in `.include`/`.incbin` (forward slashes).
fn quoted_path(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "/")
}

/// A file's text with its marker line.
fn file_text(lines: &[SourceLine]) -> String {
    let body: String = lines.iter().map(|l| format!("{}\n", l.text)).collect();
    format!("{MARKER}; checksum {:016x}\n{body}", checksum(&body))
}

pub(crate) fn render(
    a: &Analysis,
    rom_name: &str,
    source: &Path,
    patches: Option<&Patches>,
) -> Rendered {
    let mut stops: Vec<BTreeSet<usize>> = a
        .memory
        .banks
        .iter()
        .map(|b| BTreeSet::from([b.end]))
        .collect();
    let keys = a
        .labels
        .keys()
        .chain(a.comments.keys())
        .chain(a.operands.keys());
    for loc in keys {
        // A word is never split: names inside it are defined relative to it.
        if !a.in_word(*loc) {
            stops[loc.bank].insert(loc.offset);
        }
    }
    for region in a.regions.iter().flatten() {
        stops[region.bank].extend([region.start, region.end]);
    }
    for (loc, insn) in &a.insns {
        stops[loc.bank].insert(loc.offset);
        // An instruction of the fixed pair may end in the next bank.
        if let Some(last) = a.memory.step(*loc, insn.len - 1) {
            stops[last.bank].insert(last.offset + 1);
        }
    }
    for (bank, ranges) in patches.iter().flat_map(|p| p.ranges.iter().enumerate()) {
        for range in ranges {
            stops[bank].extend([range.start, range.end]);
        }
    }
    let mut w = Writer {
        a,
        lines: Vec::new(),
        used: BTreeSet::new(),
        stops: stops.into_iter().map(|s| s.into_iter().collect()).collect(),
        patches,
        used_labels: BTreeMap::new(),
    };
    // Names in operand overrides must be defined too.
    let names: HashMap<&str, Loc> = a
        .labels
        .iter()
        .flat_map(|(loc, labels)| labels.iter().map(move |l| (l.name.as_str(), *loc)))
        .collect();
    for (loc, expr) in &a.operands {
        if patches.is_some_and(|p| p.range_at(*loc).is_none()) {
            continue;
        }
        for word in expr.split(|c: char| !(c.is_ascii_alphanumeric() || c == '_')) {
            if let Some(label) = names.get(word) {
                w.used_labels.insert(word.to_owned(), *label);
            } else if a.symbols.iter().any(|s| s.name == word) {
                w.used.insert(word.to_owned());
            }
        }
    }
    // Where the fixed pair starts, after its blank separator line: the
    // second-to-last bank continues into the last with `.catbank`.
    let pair = a.memory.pair;
    let mut catbank = None;
    for bank in a.memory.prg_banks() {
        if pair == Some(bank.index) {
            catbank = Some(w.lines.len() + 1);
        }
        w.prg_bank(bank.index);
    }
    let catbank = catbank.filter(|at| *at <= w.lines.len());
    let mut body = std::mem::take(&mut w.lines);
    let chr_path = super::chr_path(source);
    let chr = w.chr_banks(&quoted_path(&chr_path));
    // An included CHR ROM is at the end of the main file; there are no bank
    // files of CHR banks unless they are written as data.
    let mut chr_lines = std::mem::take(&mut w.lines);
    if chr.is_none() {
        body.append(&mut chr_lines);
    }
    w.include_base();
    let base = std::mem::take(&mut w.lines);
    let mut head = Vec::new();
    let mut push = |text: String| {
        head.push(SourceLine {
            bank: None,
            address: None,
            size: 0,
            bytes: String::new(),
            text,
        })
    };
    push(format!("{SOURCE_LINE}{}", one_line(rom_name)));
    if let Some(data) = &chr {
        push(format!("{CHR_LINE}{:016x}", fnv(data.iter().copied())));
    }
    if let Some(p) = patches {
        push(format!(
            "; The base ROM {} is included below; the changed ranges are written over it.",
            p.path
        ));
    }
    match a.memory.format {
        RomFormat::Nes => {
            let h = &a.memory.header;
            push(String::new());
            push(format!("{INDENT}.inesprg {}", h[4]));
            push(format!("{INDENT}.ineschr {}", h[5]));
            push(format!("{INDENT}.inesmap {}", (h[6] >> 4) | (h[7] & 0xf0)));
            push(format!("{INDENT}.inesmir {}", h[6] & 0x0f));
        }
        RomFormat::Bin | RomFormat::Fragment => {
            push("; Assemble with -raw (no iNES header).".into())
        }
    }
    let symbols: Vec<_> = a
        .symbols
        .iter()
        .filter(|s| s.user || w.used.contains(&s.name))
        .collect();
    if !symbols.is_empty() {
        push(String::new());
        for s in symbols {
            let value = if s.value < 0x100 {
                format!("${:02X}", s.value)
            } else {
                format!("${:04X}", s.value)
            };
            let mut text = format!("{:<15} = {value}", s.name);
            if let Some(comment) = &s.comment {
                text.push_str(&format!(" ; {}", one_line(comment)));
            }
            push(text);
        }
    }
    // Labels of a ROM hack's unchanged ranges, which the source does not contain.
    let outside: Vec<(String, u32)> = w
        .used_labels
        .iter()
        .filter(|(_, loc)| patches.is_some_and(|p| p.range_at(**loc).is_none()))
        .map(|(name, loc)| (name.clone(), a.memory.address(*loc)))
        .collect();
    if !outside.is_empty() {
        push(String::new());
        push("; Labels in the unchanged ranges".into());
        for (name, address) in outside {
            push(format!("{name:<15} = {}", hex4(address)));
        }
    }
    if !base.is_empty() {
        push(String::new());
        head.extend(base);
    }
    let size: usize = head
        .iter()
        .chain(&body)
        .chain(&chr_lines)
        .map(|l| l.text.len() + 1)
        .sum();
    let split = a.options.split_banks.unwrap_or(size > SPLIT_SIZE);
    let main_line = |text: String| SourceLine {
        bank: None,
        address: None,
        size: 0,
        bytes: String::new(),
        text,
    };
    let catbank_line = |first: usize| main_line(format!("{INDENT}.catbank {}", hex2(first as u32)));
    let mut files = Vec::new();
    let mut lines = head.clone();
    if split {
        // One file per bank (one for the fixed pair), included from the main file.
        let file_of = |bank: usize| match pair {
            Some(first) if bank == first + 1 => first,
            _ => bank,
        };
        let mut banks: Vec<(usize, Vec<SourceLine>)> = Vec::new();
        for line in body {
            let bank = file_of(line.bank.unwrap_or_default());
            match banks.last_mut() {
                Some((b, lines)) if *b == bank => lines.push(line),
                _ => banks.push((bank, vec![line])),
            }
        }
        if !banks.is_empty() {
            head.push(main_line(String::new()));
        }
        for (bank, mut bank_lines) in banks {
            // The blank separator line belongs to the main file.
            if bank_lines.first().is_some_and(|l| l.text.is_empty()) {
                bank_lines.remove(0);
            }
            let path = if pair == Some(bank) {
                head.push(catbank_line(bank));
                lines.push(catbank_line(bank));
                super::bank_pair_path(source, bank)
            } else {
                super::bank_path(source, bank)
            };
            head.push(main_line(format!(
                "{INDENT}.include \"{}\"",
                quoted_path(&path)
            )));
            files.push((path, file_text(&bank_lines)));
            lines.extend(bank_lines);
        }
    } else {
        if let (Some(at), Some(first)) = (catbank, pair) {
            body.insert(at, catbank_line(first));
        }
        lines.extend(body.iter().cloned());
        head.extend(body);
    }
    lines.extend(chr_lines.iter().cloned());
    head.extend(chr_lines);
    files.insert(0, (source.to_owned(), file_text(&head)));
    Rendered {
        files,
        lines,
        chr: chr.map(|data| (chr_path, data)),
    }
}

fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn hex2(value: u32) -> String {
    format!("${value:02X}")
}

fn hex4(value: u32) -> String {
    format!("${value:04X}")
}

impl Writer<'_> {
    fn push(&mut self, bank: usize, address: Option<u32>, size: usize, text: String) {
        let memory = &self.a.memory;
        let image = &memory.banks[bank];
        let bytes = match address {
            Some(address) if size > 0 => {
                let shown: Vec<u8> = if image.chr {
                    let offset = address as usize;
                    image.data[offset..offset + size.min(SHOWN_BYTES)].to_vec()
                } else {
                    // An instruction of the fixed pair may end in the next bank.
                    let loc = Loc {
                        bank,
                        offset: (address - image.org) as usize,
                    };
                    (0..size.min(SHOWN_BYTES))
                        .map_while(|n| memory.step(loc, n))
                        .map(|l| memory.byte(l))
                        .collect()
                };
                let mut hex = crate::inspect::hex(&shown);
                if size > SHOWN_BYTES {
                    hex.push_str(" ..");
                }
                hex
            }
            _ => String::new(),
        };
        self.lines.push(SourceLine {
            bank: Some(bank),
            address: address.map(Address),
            size,
            bytes,
            text,
        });
    }

    fn mnemonic(&self, name: &str) -> String {
        if self.a.options.uppercase {
            name.to_owned()
        } else {
            name.to_ascii_lowercase()
        }
    }

    fn index(&self, register: &str) -> String {
        if self.a.options.uppercase {
            register.to_owned()
        } else {
            register.to_ascii_lowercase()
        }
    }

    fn prg_bank(&mut self, index: usize) {
        let bank = &self.a.memory.banks[index];
        let (org, start, end) = (bank.org, bank.start, bank.end);
        // Bytes at the start that an instruction of the previous bank of the
        // fixed pair ends with: no `.bank` or `.org` can split it, so the
        // assembler continues into this bank (`.catbank`).
        let continued = self.continued(index);
        let Some(patches) = self.patches else {
            if continued > 0 {
                self.boundary(index);
            } else {
                self.push(index, None, 0, String::new());
                self.push(index, None, 0, format!("{INDENT}.bank {index}"));
                self.push(
                    index,
                    None,
                    0,
                    format!("{INDENT}.org {}", hex4(org + start as u32)),
                );
            }
            self.code_and_data(index, start + continued, end);
            return;
        };
        // A ROM hack: only the changed ranges, written over the base ROM
        // that the main file includes. A bank without changes has no lines.
        let mut opened = false;
        for range in &patches.ranges[index] {
            // A range ending with such an instruction continues into this one.
            let continues = range.start < continued;
            if !continues {
                self.push(index, None, 0, String::new());
                if !opened {
                    self.push(index, None, 0, format!("{INDENT}.bank {index}"));
                }
                opened = true;
            }
            let address = org + range.start as u32;
            for line in range.comment.iter().flat_map(|c| c.lines()) {
                let text = format!("; {line}").trim_end().to_owned();
                self.push(index, Some(address), 0, text);
            }
            if continues {
                self.boundary(index);
                self.code_and_data(index, continued, range.end);
            } else {
                self.push(index, None, 0, format!("{INDENT}.org {}", hex4(address)));
                self.code_and_data(index, range.start, range.end);
            }
        }
    }

    /// How many bytes at the start of `bank` belong to an instruction that
    /// starts in the previous bank of the fixed pair.
    fn continued(&self, bank: usize) -> usize {
        let start = Loc { bank, offset: 0 };
        (1..=2)
            .find_map(|n| {
                let insn = self.a.insns.get(&self.a.memory.back(start, n)?)?;
                (insn.len > n).then(|| insn.len - n)
            })
            .unwrap_or(0)
    }

    /// The note where the last bank of the fixed pair starts inside an instruction.
    fn boundary(&mut self, index: usize) {
        let org = self.a.memory.banks[index].org;
        self.push(
            index,
            Some(org),
            0,
            format!(
                "; Bank {index} starts at {}, inside the instruction above",
                hex4(org)
            ),
        );
    }

    /// The instructions and data of `start..end` of a PRG bank.
    fn code_and_data(&mut self, index: usize, start: usize, end: usize) {
        let mut offset = start;
        while offset < end {
            let loc = Loc {
                bank: index,
                offset,
            };
            self.prelude(loc);
            let size = match self.a.class[index][offset] {
                Class::Insn => self.instruction(loc),
                _ => self.data(loc),
            };
            offset += size;
        }
    }

    /// For a ROM hack, the `.incbin` of the base ROM's PRG banks that the
    /// changed ranges are written over: one per run of banks the base holds
    /// in the same order (one unless banks were inserted). The base's header
    /// and CHR banks are left out: the CHR file holds the whole CHR ROM.
    /// Bytes the base lacks are changed bytes, so the ranges write them.
    fn include_base(&mut self) {
        let Some(patches) = self.patches else {
            return;
        };
        // (first bank, offset in the bank, offset in the base file, size)
        let mut runs: Vec<(usize, usize, usize, usize)> = Vec::new();
        for bank in self.a.memory.prg_banks() {
            let Some(other) = patches.base_bank[bank.index].map(|b| &patches.base.banks[b]) else {
                continue;
            };
            let start = bank.start.max(other.start);
            let end = bank.end.min(other.end);
            if start >= end {
                continue;
            }
            let file = patches.header_len + other.index * BANK_SIZE + start;
            let position = bank.index * BANK_SIZE + start;
            match runs.last_mut() {
                Some((first, offset, from, size))
                    if *first * BANK_SIZE + *offset + *size == position
                        && *from + *size == file =>
                {
                    *size += end - start;
                }
                _ => runs.push((bank.index, start, file, end - start)),
            }
        }
        for (index, offset, file, size) in runs {
            let org = self.a.memory.banks[index].org + offset as u32;
            self.push(index, None, 0, format!("{INDENT}.bank {index}"));
            self.push(index, None, 0, format!("{INDENT}.org {}", hex4(org)));
            let text = format!("{INDENT}.incbin \"{}\", {file}, {size}", patches.path);
            self.push(index, Some(org), size, text);
        }
    }

    /// The name of a ROM location, noting that the source uses it.
    fn rom_name(&mut self, loc: Loc) -> Option<String> {
        let name = self.a.rom_name(loc)?;
        let labelled = if self.a.labels.contains_key(&loc) {
            Some(loc)
        } else {
            self.a.containing(loc)
        };
        if let Some(labelled) = labelled
            && let Some(label) = self.a.labels.get(&labelled).and_then(|l| l.first())
        {
            self.used_labels.insert(label.name.clone(), labelled);
        }
        Some(name)
    }

    /// Comments and labels before the line at `loc`.
    fn prelude(&mut self, loc: Loc) {
        let address = self.a.memory.address(loc);
        let mut above = Vec::new();
        if let Some(region) = self.a.region_at(loc).filter(|r| r.start == loc.offset)
            && let Some(comment) = &region.comment
        {
            above.extend(comment.lines().map(str::to_owned));
        }
        let size = self.a.insns.get(&loc).map_or(1, |i| i.len);
        for inner in self.covered(loc, size) {
            if let Some((lines, _)) = self.a.comments.get(&inner) {
                above.extend(lines.iter().cloned());
            }
        }
        for line in above {
            self.push(
                loc.bank,
                Some(address),
                0,
                format!("; {line}").trim_end().to_owned(),
            );
        }
        for label in self.a.labels.get(&loc).into_iter().flatten() {
            self.label_comment(loc.bank, address, label);
            self.push(loc.bank, Some(address), 0, format!("{}:", label.name));
        }
    }

    /// The comment lines of a label.
    fn label_comment(&mut self, bank: usize, address: u32, label: &Label) {
        for line in label.comment.iter().flat_map(|c| c.lines()) {
            let text = format!("; {line}").trim_end().to_owned();
            self.push(bank, Some(address), 0, text);
        }
    }

    /// The comment at the end of the line covering `loc..loc+size`.
    fn line_comment(&self, loc: Loc, size: usize) -> String {
        let mut parts = Vec::new();
        if self.a.options.address_comments {
            parts.push(hex4(self.a.memory.address(loc)));
        }
        // A data read through a window: the address is a number, not a
        // label of one bank.
        if let Some(d) = self.a.dynamic.get(&loc) {
            parts.push(match self.a.dynamic_bank(loc) {
                Some(bank) => format!(
                    "dynamic: reads the bank switched in at {} (bank {bank} on every path traced)",
                    hex4(d.window)
                ),
                None => format!("dynamic: reads the bank switched in at {}", hex4(d.window)),
            });
        }
        for inner in self.covered(loc, size) {
            if let Some((_, line)) = self.a.comments.get(&inner) {
                parts.extend(line.iter().cloned());
            }
        }
        if parts.is_empty() {
            String::new()
        } else {
            format!(" ; {}", parts.join(" "))
        }
    }

    /// The locations of the `size` bytes from `loc` (into the next bank of
    /// the fixed pair).
    fn covered(&self, loc: Loc, size: usize) -> Vec<Loc> {
        (0..size)
            .filter_map(|n| self.a.memory.step(loc, n))
            .collect()
    }

    fn instruction(&mut self, loc: Loc) -> usize {
        let insn = self.a.insns[&loc];
        let mnemonic = self.mnemonic(insn.mnemonic.name());
        let operand = match self.a.operands.get(&loc) {
            Some(expr) => Some(expr.clone()),
            None => self.operand(loc, insn),
        };
        let mut text = match operand {
            Some(operand) => format!("{INDENT}{mnemonic} {operand}"),
            None => format!("{INDENT}{mnemonic}"),
        };
        text.push_str(&self.line_comment(loc, insn.len));
        let address = self.a.memory.address(loc);
        self.push(loc.bank, Some(address), insn.len, text);
        // Labels inside the instruction (skip tricks) are defined relative to it.
        for (n, inner) in self.covered(loc, insn.len).into_iter().enumerate().skip(1) {
            let Some(base) = self.a.labels.get(&loc).and_then(|l| l.first()) else {
                continue;
            };
            for label in self.a.labels.get(&inner).into_iter().flatten() {
                let base = base.name.clone();
                let inner_address = address + n as u32;
                self.label_comment(loc.bank, inner_address, label);
                self.push(
                    loc.bank,
                    Some(inner_address),
                    0,
                    format!("{} = {base}+{n}", label.name),
                );
            }
        }
        insn.len
    }

    fn operand(&mut self, loc: Loc, insn: Insn) -> Option<String> {
        let (x, y) = (self.index("X"), self.index("Y"));
        let value = insn.value;
        Some(match insn.mode {
            Mode::Imp => return None,
            Mode::Acc => self.index("A"),
            Mode::Imm => format!("#{}", hex2(value)),
            Mode::Zp | Mode::Zpx | Mode::Zpy | Mode::Zi | Mode::Zix | Mode::Ziy => {
                let expr = match self.a.memory.resolve(Some(loc.bank), value) {
                    super::analysis::Resolved::Rom(t) => self.rom_name(t),
                    _ => self.symbol(value),
                }
                .unwrap_or_else(|| hex2(value));
                match insn.mode {
                    Mode::Zp => format!("<{expr}"),
                    Mode::Zpx => format!("<{expr},{x}"),
                    Mode::Zpy => format!("<{expr},{y}"),
                    Mode::Zi => format!("[{expr}]"),
                    Mode::Zix => format!("[{expr},{x}]"),
                    _ => format!("[{expr}],{y}"),
                }
            }
            Mode::Rel => {
                let address = self.a.memory.address(loc);
                let operand = self
                    .a
                    .memory
                    .step(loc, 1)
                    .map_or(0, |l| self.a.memory.byte(l));
                let delta = i64::from(operand as i8) + 2;
                // A branch that wraps around $FFFF/$0000 is written relative to `*`.
                if !(0..=0xffff).contains(&(i64::from(address) + delta)) {
                    format!("*{delta:+}")
                } else {
                    self.target(loc, value)
                }
            }
            _ => {
                // A write to $8000-$FFFF goes to the mapper, not to the ROM
                // byte a label would name.
                let mapper = value >= 0x8000 && writes(insn.mnemonic);
                let expr = if mapper {
                    hex4(value)
                } else {
                    self.target(loc, value)
                };
                match insn.mode {
                    Mode::Ax => format!("{expr},{x}"),
                    Mode::Ay => format!("{expr},{y}"),
                    Mode::Ind => format!("[{expr}]"),
                    Mode::Ix => format!("[{expr},{x}]"),
                    _ => expr,
                }
            }
        })
    }

    /// A name for `value` as referred to from `from`, or the number.
    fn target(&mut self, from: Loc, value: u32) -> String {
        match self.a.target_of(from, value) {
            Target::Rom(t) => self.rom_name(t),
            Target::Ambiguous(_) | Target::Dynamic(_) => None,
            Target::Outside(v) => self.symbol(v),
        }
        .unwrap_or_else(|| hex4(value))
    }

    fn symbol(&mut self, value: u32) -> Option<String> {
        let name = self.a.symbol_name(value)?;
        let base = name.split('+').next().unwrap_or(&name).to_owned();
        self.used.insert(base);
        Some(name)
    }

    /// One line of data from `loc`; returns the bytes it covers.
    fn data(&mut self, loc: Loc) -> usize {
        let region = self.a.region_at(loc).cloned();
        let limit = self.run_end(loc);
        let kind = region.as_ref().map_or(RegionType::Bytes, |r| r.kind);
        let columns = region
            .as_ref()
            .and_then(|r| r.columns)
            .unwrap_or(self.a.options.data_per_line);
        let byte = |offset: usize| self.a.memory.byte(loc.at(offset));
        let start = loc.offset;
        let (directive, items, size): (&str, Vec<String>, usize) = match kind {
            RegionType::Words | RegionType::Pointers if limit - start >= 2 => {
                let count = ((limit - start) / 2).min(columns);
                let items = (0..count)
                    .map(|i| {
                        let element = loc.at(start + 2 * i);
                        if let Some(expr) = self.a.operands.get(&element) {
                            return expr.clone();
                        }
                        let stored = u32::from(byte(start + 2 * i))
                            | u32::from(byte(start + 2 * i + 1)) << 8;
                        match (&region, kind) {
                            (Some(r), RegionType::Pointers) => self.pointer(element, stored, r),
                            _ => hex4(stored),
                        }
                    })
                    .collect();
                (".dw", items, 2 * count)
            }
            RegionType::LowBytes | RegionType::HighBytes => {
                let count = (limit - start).min(columns);
                let r = region.as_ref().expect("table region");
                let items = (0..count)
                    .map(|i| {
                        let element = loc.at(start + i);
                        match self.a.operands.get(&element) {
                            Some(expr) => expr.clone(),
                            None => self.table_byte(element, r),
                        }
                    })
                    .collect();
                (".db", items, count)
            }
            RegionType::Text => match self.a.operands.get(&loc) {
                Some(expr) => (".db", vec![expr.clone()], 1),
                None => {
                    let (items, size) = self.text(loc, limit);
                    (".db", items, size)
                }
            },
            _ => {
                let run = (start..limit)
                    .take_while(|o| byte(*o) == byte(start))
                    .count();
                if run >= FILL_RUN && !self.a.operands.contains_key(&loc) {
                    let text = match byte(start) {
                        0 => format!("{INDENT}.ds {run}"),
                        fill => format!("{INDENT}.ds {run}, {}", hex2(u32::from(fill))),
                    };
                    let text = text + &self.line_comment(loc, run);
                    self.push(loc.bank, Some(self.a.memory.address(loc)), run, text);
                    return run;
                }
                // Stop before a long run, so that it becomes `.ds`.
                let mut count = 0;
                while count < columns && start + count < limit {
                    let o = start + count;
                    if count > 0
                        && (o..limit).take_while(|p| byte(*p) == byte(o)).count() >= FILL_RUN
                    {
                        break;
                    }
                    count += 1;
                }
                let items = (0..count)
                    .map(|i| match self.a.operands.get(&loc.at(start + i)) {
                        Some(expr) => expr.clone(),
                        None => hex2(u32::from(byte(start + i))),
                    })
                    .collect();
                (".db", items, count)
            }
        };
        let text = format!(
            "{INDENT}{directive} {}{}",
            items.join(", "),
            self.line_comment(loc, size)
        );
        self.push(loc.bank, Some(self.a.memory.address(loc)), size, text);
        for offset in loc.offset + 1..loc.offset + size {
            let inner = loc.at(offset);
            if !self.a.in_word(inner) {
                continue;
            }
            let address = self.a.memory.address(inner);
            for line in self
                .a
                .comments
                .get(&inner)
                .map_or(&[][..], |(above, _)| above.as_slice())
            {
                let text = format!("; {line}").trim_end().to_owned();
                self.push(loc.bank, Some(address), 0, text);
            }
            let Some(base) = self
                .a
                .labels
                .get(&loc.at(offset - 1))
                .and_then(|l| l.first())
            else {
                continue;
            };
            let base = base.name.clone();
            for label in self.a.labels.get(&inner).into_iter().flatten() {
                self.label_comment(loc.bank, address, label);
                self.push(
                    loc.bank,
                    Some(address),
                    0,
                    format!("{} = {base}+1", label.name),
                );
            }
        }
        size
    }

    /// Where the data line from `loc` must end: the end of its region or of
    /// the unclassified bytes, or the next label, comment or operand.
    fn run_end(&self, loc: Loc) -> usize {
        let stops = &self.stops[loc.bank];
        stops[stops.partition_point(|s| *s <= loc.offset)]
    }

    fn pointer(&mut self, element: Loc, stored: u32, region: &Region) -> String {
        self.adjusted_target(element, stored, region.adjust)
            .unwrap_or_else(|| hex4(stored))
    }

    /// `label+adjust` for a stored table value, unless the value wraps
    /// around $FFFF (the expression would then not fit).
    fn adjusted_target(&mut self, from: Loc, stored: u32, adjust: i32) -> Option<String> {
        let target = (i64::from(stored) - i64::from(adjust)).rem_euclid(0x10000);
        if target + i64::from(adjust) != i64::from(stored) {
            return None;
        }
        let name = match self.a.target_of(from, target as u32) {
            Target::Rom(t) => self.rom_name(t),
            Target::Outside(v) => self.symbol(v),
            Target::Ambiguous(_) | Target::Dynamic(_) => None,
        }?;
        Some(adjusted(&name, adjust))
    }

    /// A byte of a low/high table as `LOW(label)` / `HIGH(label)`.
    fn table_byte(&mut self, element: Loc, region: &Region) -> String {
        let raw = hex2(u32::from(self.a.memory.byte(element)));
        let index = element.offset - region.start;
        let low = if region.kind == RegionType::LowBytes {
            Some(region.clone())
        } else {
            self.a.regions[region.bank]
                .iter()
                .find(|r| r.kind == RegionType::LowBytes && r.pair == Some(region.start))
                .cloned()
        };
        let Some(low) = low else {
            return raw;
        };
        let low_loc = element.at(low.start + index);
        let high = element.at(low.pair.unwrap_or(low.start) + index);
        let stored = u32::from(u16::from_le_bytes([
            self.a.memory.byte(low_loc),
            self.a.memory.byte(high),
        ]));
        let function = if region.kind == RegionType::LowBytes {
            "LOW"
        } else {
            "HIGH"
        };
        self.adjusted_target(low_loc, stored, low.adjust)
            .map_or(raw, |expr| format!("{function}({expr})"))
    }

    fn text(&self, loc: Loc, limit: usize) -> (Vec<String>, usize) {
        let end = limit.min(loc.offset + TEXT_PER_LINE);
        let mut items = Vec::new();
        let mut text = String::new();
        for offset in loc.offset..end {
            let b = self.a.memory.byte(loc.at(offset));
            if (0x20..0x7f).contains(&b) && b != b'"' && b != b'\\' {
                text.push(char::from(b));
            } else {
                if !text.is_empty() {
                    items.push(format!("\"{}\"", std::mem::take(&mut text)));
                }
                items.push(hex2(u32::from(b)));
            }
        }
        if !text.is_empty() {
            items.push(format!("\"{text}\""));
        }
        (items, end - loc.offset)
    }

    fn chr_banks(&mut self, chr_name: &str) -> Option<Vec<u8>> {
        let banks: Vec<usize> = self
            .a
            .memory
            .banks
            .iter()
            .filter(|b| b.chr)
            .map(|b| b.index)
            .collect();
        let first = *banks.first()?;
        if self.a.options.chr == ChrMode::Incbin {
            // The whole CHR ROM (of a ROM hack too, changed or not) is
            // included once from one file in the original order (CHR editors
            // read it whole), at the end of the main file.
            let mut file = Vec::new();
            for &index in &banks {
                let bank = &self.a.memory.banks[index];
                file.extend_from_slice(&bank.data[bank.start..bank.end]);
            }
            self.push(first, None, 0, String::new());
            self.push(first, None, 0, format!("{INDENT}.bank {first}"));
            self.push(first, None, 0, format!("{INDENT}.org $0000"));
            let text = format!("{INDENT}.incbin \"{chr_name}\"");
            self.push(first, Some(0), file.len(), text);
            return Some(file);
        }
        // Written as data, each CHR bank is a bank of its own.
        let a = self.a;
        for index in banks {
            let bank = &a.memory.banks[index];
            let data = &bank.data[bank.start..bank.end];
            self.push(index, None, 0, String::new());
            self.push(index, None, 0, format!("{INDENT}.bank {index}"));
            self.push(index, None, 0, format!("{INDENT}.org $0000"));
            let mut offset = 0;
            while offset < data.len() {
                let run = data[offset..]
                    .iter()
                    .take_while(|b| **b == data[offset])
                    .count();
                if run >= FILL_RUN {
                    let text = match data[offset] {
                        0 => format!("{INDENT}.ds {run}"),
                        fill => format!("{INDENT}.ds {run}, {}", hex2(u32::from(fill))),
                    };
                    self.push(index, Some(offset as u32), run, text);
                    offset += run;
                    continue;
                }
                let count = a.options.data_per_line.min(data.len() - offset);
                let count = (1..count)
                    .find(|i| {
                        data[offset + i..]
                            .iter()
                            .take_while(|b| **b == data[offset + i])
                            .count()
                            >= FILL_RUN
                    })
                    .unwrap_or(count);
                let items: Vec<String> = data[offset..offset + count]
                    .iter()
                    .map(|b| hex2(u32::from(*b)))
                    .collect();
                self.push(
                    index,
                    Some(offset as u32),
                    count,
                    format!("{INDENT}.db {}", items.join(", ")),
                );
                offset += count;
            }
        }
        None
    }
}

/// `name` plus a pointer table adjustment, as in `label-1`.
fn adjusted(name: &str, adjust: i32) -> String {
    match adjust {
        0 => name.to_owned(),
        _ => format!("{name}{adjust:+}"),
    }
}
